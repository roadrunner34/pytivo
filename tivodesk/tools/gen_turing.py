"""Generate Go tables and cross-implementation test vectors from pyTivo.

pyTivo's turing.py and metadata.py are the reference. This script copies
the cipher tables into Go source and records what the Python code produces,
so the Go tests compare against Python rather than against themselves.

Run from the repo root:  python tivodesk/tools/gen_turing.py
"""
import hashlib
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

import metadata  # noqa: E402
import turing  # noqa: E402

CRYPT = os.path.join(ROOT, 'tivodesk', 'internal', 'tivocrypt')


def go_table(name, values, typ, width, per_line):
    lines = ['var %s = [256]%s{' % (name, typ)]
    for i in range(0, len(values), per_line):
        row = ', '.join('0x%0*x' % (width, v) for v in values[i:i + per_line])
        lines.append('\t' + row + ',')
    lines.append('}')
    return '\n'.join(lines)


def write_tables():
    out = [
        '// Code generated by tools/gen_turing.py from pyTivo turing.py. DO NOT EDIT.',
        '',
        'package turing',
        '',
        '// qbox is the 8->32 S-box from Queensland University of Technology.',
        go_table('qbox', turing._QBOX, 'uint32', 8, 6),
        '',
        '// multab is the multiplication table for 0xd02b4367.',
        go_table('multab', turing._MULTAB, 'uint32', 8, 6),
        '',
        '// sbox is the basic 8->8 S-box.',
        go_table('sbox', turing._SBOX, 'uint8', 2, 12),
        '',
    ]
    path = os.path.join(CRYPT, 'turing', 'tables.go')
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(out))


def write_vectors():
    cases = []
    specs = [
        ('sha1 key and iv', hashlib.sha1(b'key').digest(),
         hashlib.sha1(b'iv').digest()),
        ('16-byte key, 8-byte iv', bytes(range(16)), bytes(range(100, 108))),
        ('32-byte key, 16-byte iv', bytes(range(32)), bytes(range(200, 216))),
        ('4-byte key, 4-byte iv', b'\x01\x02\x03\x04', b'\xff\xfe\xfd\xfc'),
    ]
    for name, key, iv in specs:
        stream = turing.Turing(key, iv).gen(0, 400)
        skips = {}
        for skip in (0, 1, 19, 20, 21, 37, 40, 123):
            skips[str(skip)] = turing.Turing(key, iv).gen(skip, 40).hex()
        cases.append({'name': name, 'key': key.hex(), 'iv': iv.hex(),
                      'stream': stream.hex(), 'skips': skips})
    path = os.path.join(CRYPT, 'turing', 'testdata', 'vectors.json')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\n') as f:
        json.dump(cases, f, indent=1)


def write_tivo_header():
    """A synthetic .tivo header, built the same way tests/test_turing.py
    builds one, plus what metadata._tdcat_py reads back from it."""
    mak = '1234567890'
    xml_key = b'0123456789abcdef'
    details = (b'<?xml version="1.0" encoding="utf-8"?><TvBusMarshalledStruct>'
               b'<showing><program><title>Caf\xc3\xa9</title></program>'
               b'</showing></TvBusMarshalledStruct>')

    hexmak = hashlib.md5(('tivo:TiVo DVR:' + mak).encode()).hexdigest()
    key = hashlib.sha1(hexmak.encode() + xml_key).digest()[:16] + b'\0' * 4
    turkey = hashlib.sha1(key[:17]).digest()
    turiv = hashlib.sha1(key).digest()

    def chunk(cid, enc, data):
        return struct.pack('>LLHH', len(data) + 12, len(data), cid, enc) + data

    chunk1 = chunk(1, 0, b'unused')
    chunk2_start = 16 + len(chunk1) + 12
    encrypted = turing.Turing(turkey, turiv).crypt(details, chunk2_start)
    body = chunk1 + chunk(2, 1, encrypted) + chunk(3, 0, xml_key)
    header = b'TiVo' + struct.pack('>HHHLH', 4, 13, 0, 16 + len(body), 3)

    folder = os.path.join(CRYPT, 'tivofile', 'testdata')
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, 'synthetic.tivo')
    with open(path, 'wb') as f:
        f.write(header + body + b'\0' * 64)

    readback = metadata._tdcat_py(path, mak)
    assert readback == details
    with open(os.path.join(folder, 'synthetic.json'), 'w', newline='\n') as f:
        json.dump({'mak': mak, 'details': readback.decode('utf-8')}, f, indent=1)


if __name__ == '__main__':
    os.makedirs(os.path.join(CRYPT, 'turing'), exist_ok=True)
    write_tables()
    write_vectors()
    write_tivo_header()
    print('wrote tables.go, vectors.json, synthetic.tivo')
